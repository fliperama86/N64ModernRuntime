static void pak_init() {
    if (pak_initialized) return;
    fprintf(stderr, "[PAK] pak_init: checking save buffer...\n");
    uint8_t check[4];
    save_read_ptr(check, 0x100, 4);
    if (check[0] == 0 && check[1] == 0 && check[2] == 0 && check[3] == 0) {
        format_empty_pak();
    } else {
        fprintf(stderr, "[PAK] Save buffer already has data (inode[0..3]=%02X %02X %02X %02X)\n",
                check[0], check[1], check[2], check[3]);
    }
    pak_initialized = true;
}

// ── Public API: block read/write + CRC ───────────────────────────────

static void wait_for_save_buffer() {
    // Spin-wait for the save buffer to be allocated. This happens very early
    // in startup — typically within the first few frames. Without this wait,
    // the game's first pak read returns zeros → "pak abnormality".
    if (!pak_save_ready()) {
        fprintf(stderr, "[PAK] Waiting for save buffer...\n");
        while (!pak_save_ready()) {
            // Yield to avoid busy-spinning
            std::this_thread::yield();
        }
        fprintf(stderr, "[PAK] Save buffer ready\n");
    }
}

extern "C" void pak_read(uint16_t addr, uint8_t* out, int count) {
    wait_for_save_buffer();
    std::lock_guard lock{pak_mutex};
    pak_init();
    if (addr + count <= PFS_TOTAL_SIZE) {
        save_read_ptr(out, addr, count);
    } else if (addr >= 0x8000 && addr < 0x8100) {
        int offset = addr - 0x8000;
        int safe = (offset + count <= 256) ? count : 256 - offset;
        if (safe > 0) memcpy(out, pak_probe_area + offset, safe);
        if (safe < count) memset(out + safe, 0, count - safe);
    } else {
        memset(out, 0, count);
    }
}

extern "C" void pak_write(uint16_t addr, const uint8_t* in, int count) {
    wait_for_save_buffer();
    std::lock_guard lock{pak_mutex};
    pak_init();
    if (addr + count <= PFS_TOTAL_SIZE) {
        save_write_ptr(in, addr, count);
    } else if (addr >= 0x8000 && addr < 0x8100) {
        int offset = addr - 0x8000;
        int safe = (offset + count <= 256) ? count : 256 - offset;
        if (safe > 0) memcpy(pak_probe_area + offset, in, safe);
    }
}

// N64 Controller Pak data CRC-8 (polynomial 0x85).
// Used in PIF responses so the game's __osContRamRead can verify data integrity.
// Algorithm from mupen64plus game_controller.c.
extern "C" uint8_t pak_data_crc(const uint8_t* data, int size) {
    uint8_t crc = 0;
    for (int i = 0; i <= size; ++i) {
        for (int mask = 0x80; mask >= 1; mask >>= 1) {
            uint8_t xor_tap = (crc & 0x80) ? 0x85 : 0x00;
            crc <<= 1;
            if (i != size && (data[i] & mask)) crc |= 1;
            crc ^= xor_tap;
        }
    }
    return crc;
}
