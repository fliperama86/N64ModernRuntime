// ── Virtual Controller Pak (Memory Pak) — Storage Backend ──────────
//
// Provides a properly formatted 32KB N64 Controller Pak image backed
// by the runtime's save buffer. The game's recompiled PFS SDK code
// (osPfsInitPak, osPfsFindFile, osPfsAllocateFile, etc.) operates on
// this image through the PIF command handler in __osSiRawStartDma_recomp.
//
// We do NOT override any PFS API functions. The only interface is:
//   pak_read(addr, out, count)  — read bytes from pak image
//   pak_write(addr, in, count)  — write bytes to pak image
//   pak_data_crc(data, size)    — CRC-8 for PIF response status byte

#include <cstdio>
#include <cstring>
#include <mutex>
#include <thread>

static constexpr int PFS_TOTAL_SIZE = 0x8000;
static constexpr int PFS_PAGE_SIZE = 256;

// Save buffer accessors (defined in pi.cpp)
extern void save_write_ptr(const void* in, uint32_t offset, uint32_t count);
extern void save_read_ptr(void* out, uint32_t offset, uint32_t count);
extern bool pak_save_ready();

static bool pak_initialized = false;
static std::mutex pak_mutex;

// Probe area at 0x8000-0x80FF: 256-byte RAM that echoes writes back.
// Used by the game's pak detection (write test pattern, read back, compare).
static uint8_t pak_probe_area[256] = {};

// ── Format a fresh empty Controller Pak ──────────────────────────────
